const META_PIXEL_ID = "INSERT_PIXEL_ID_HERE";
const TRACKING_QUERY_KEYS = ["fbclid", "gclid", "wbraid", "gbraid"];

function trackOrderClick() {
  if (typeof window.fbq === "function") {
    window.fbq("trackCustom", "OrderClick", {
      content_name: PRODUCT_CONFIG.productName,
      content_url: PRODUCT_CONFIG.productUrl,
      value: PRODUCT_CONFIG.priceValue,
      currency: "BDT",
    });
  }
}

function initializeMetaPixel() {
  if (!META_PIXEL_ID || META_PIXEL_ID === "INSERT_PIXEL_ID_HERE") {
    return;
  }

  (function (f, b, e, v, n, t, s) {
    if (f.fbq) return;
    n = f.fbq = function () {
      n.callMethod ? n.callMethod.apply(n, arguments) : n.queue.push(arguments);
    };
    if (!f._fbq) f._fbq = n;
    n.push = n;
    n.loaded = true;
    n.version = "2.0";
    n.queue = [];
    t = b.createElement(e);
    t.async = true;
    t.src = v;
    s = b.getElementsByTagName(e)[0];
    s.parentNode.insertBefore(t, s);
  })(window, document, "script", "https://connect.facebook.net/en_US/fbevents.js");

  window.fbq("init", META_PIXEL_ID);
  window.fbq("track", "PageView");
  window.fbq("track", "ViewContent", {
    content_name: PRODUCT_CONFIG.productName,
    content_type: "product",
    value: PRODUCT_CONFIG.priceValue,
    currency: "BDT",
  });
}

function addCampaignParameters(destination) {
  const target = new URL(destination);
  const current = new URLSearchParams(window.location.search);

  current.forEach((value, key) => {
    if (key.toLowerCase().startsWith("utm_") || TRACKING_QUERY_KEYS.includes(key.toLowerCase())) {
      target.searchParams.set(key, value);
    }
  });

  return target.toString();
}

function renderProductImages() {
  const mainImage = document.querySelector("#main-product-image");
  const thumbnailList = document.querySelector("#product-thumbnails");
  const firstImage = PRODUCT_CONFIG.images[0];
  mainImage.src = `${firstImage.src}?w=1000&q=85`;
  mainImage.alt = firstImage.alt;

  PRODUCT_CONFIG.images.forEach((image, index) => {
    const button = document.createElement("button");
    button.className = "thumbnail";
    button.type = "button";
    button.setAttribute("aria-label", `পণ্যের ছবি ${index + 1} দেখুন`);
    button.setAttribute("aria-pressed", String(index === 0));
    button.innerHTML = `<img src="${image.src}?w=128&q=70" alt="" loading="lazy" width="128" height="128">`;
    button.addEventListener("click", () => {
      mainImage.classList.add("is-changing");
      window.setTimeout(() => {
        mainImage.src = `${image.src}?w=1000&q=85`;
        mainImage.alt = image.alt;
        mainImage.classList.remove("is-changing");
      }, 120);
      thumbnailList.querySelectorAll(".thumbnail").forEach((thumbnail) => {
        thumbnail.setAttribute("aria-pressed", String(thumbnail === button));
      });
    });
    thumbnailList.append(button);
  });
}

