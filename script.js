function renderFaqs() {
  const list = document.querySelector("#faq-list");

  PRODUCT_CONFIG.faqs.forEach((faq, index) => {
    const item = document.createElement("section");
    item.className = "faq-item";
    const questionId = `faq-question-${index + 1}`;
    const answerId = `faq-answer-${index + 1}`;
    item.innerHTML = `<button class="faq-question" id="${questionId}" type="button" aria-expanded="false" aria-controls="${answerId}"><span>${faq.question}</span><span aria-hidden="true">+</span></button><div class="faq-answer" id="${answerId}" role="region" aria-labelledby="${questionId}"><p>${faq.answer}</p></div>`;
    list.append(item);
  });

  list.addEventListener("click", (event) => {
    const button = event.target.closest(".faq-question");
    if (!button) return;

    const willOpen = button.getAttribute("aria-expanded") !== "true";
    list.querySelectorAll(".faq-question").forEach((question) => {
      question.setAttribute("aria-expanded", "false");
      document.getElementById(question.getAttribute("aria-controls")).style.maxHeight = "0";
    });

    if (willOpen) {
      button.setAttribute("aria-expanded", "true");
      const answer = document.getElementById(button.getAttribute("aria-controls"));
      answer.style.maxHeight = `${answer.scrollHeight}px`;
    }
  });
}

function setupNavigation() {
  const toggle = document.querySelector(".menu-toggle");
  const navigation = document.querySelector("#main-nav");

  toggle.addEventListener("click", () => {
    const isExpanded = toggle.getAttribute("aria-expanded") === "true";
    toggle.setAttribute("aria-expanded", String(!isExpanded));
    toggle.setAttribute("aria-label", isExpanded ? "মেনু খুলুন" : "মেনু বন্ধ করুন");
    navigation.classList.toggle("is-open", !isExpanded);
  });

  navigation.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      navigation.classList.remove("is-open");
      toggle.setAttribute("aria-expanded", "false");
      toggle.setAttribute("aria-label", "মেনু খুলুন");
    });
  });
}

function setupOrderLinks() {
  document.querySelectorAll("[data-order-link]").forEach((link) => {
    link.href = addCampaignParameters(PRODUCT_CONFIG.productUrl);
    link.addEventListener("click", trackOrderClick);
  });
}

